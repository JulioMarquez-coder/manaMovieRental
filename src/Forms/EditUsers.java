    // Nombre: BtnAgregarActionPerformed
    // Propósito: Pedir los datos de un nuevo usuario por cuadros de diálogo e insertarlo en la base de datos.
    // PreCondiciones: La tabla users debe existir y aceptar los campos indicados; DBConnection debe conectar bien.
    // PostCondiciones: Si todo sale bien, se inserta un nuevo usuario con rol USER y se recarga la tabla de usuarios.
    // Argumentos: evt - evento que se genera cuando se presiona el botón "Agregar".
    // Valores: No devuelve valor, solo interactúa con la BD y actualiza la interfaz.
    private void BtnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnAgregarActionPerformed
        // TODO add your handling code here:
        // Pedir datos por ventanitas
    String firstName  = JOptionPane.showInputDialog(this, "First name:");
    if (firstName == null) return;  // Canceló

    String middleName = JOptionPane.showInputDialog(this, "Middle name (opcional):");
    if (middleName == null) middleName = "";

    String lastName   = JOptionPane.showInputDialog(this, "Last name:");
    if (lastName == null) return;

    String phone      = JOptionPane.showInputDialog(this, "Phone (opcional):");
    if (phone == null) phone = "";

    String address    = JOptionPane.showInputDialog(this, "Address (opcional):");
    if (address == null) address = "";

    String city       = JOptionPane.showInputDialog(this, "City (opcional):");
    if (city == null) city = "";

    String zipCode    = JOptionPane.showInputDialog(this, "Zip code (opcional):");
    if (zipCode == null) zipCode = "";

    String birthDate  = JOptionPane.showInputDialog(
            this, "Birth date (YYYY-MM-DD, o dejar vacío):");
    if (birthDate == null) birthDate = "";

    // Campos necesarios para login
    String username   = JOptionPane.showInputDialog(this, "Username:");
    if (username == null || username.trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "El username no puede estar vacío.");
        return;
    }

    String password   = JOptionPane.showInputDialog(this, "Password:");
    if (password == null || password.trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "La contraseña no puede estar vacía.");
        return;
    }

    // INSERT en la BD
    String sql = "INSERT INTO users (" +
                 "first_name, middle_name, last_name, phone, address, city, zip_code, " +
                 "birth_date, username, password_hash, role" +
                 ") VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)";

    try (Connection cn = DBConnection.getConnection();
         PreparedStatement ps = cn.prepareStatement(sql)) {

        ps.setString(1,  firstName);
        ps.setString(2,  middleName);
        ps.setString(3,  lastName);
        ps.setString(4,  phone);
        ps.setString(5,  address);
        ps.setString(6,  city);
        ps.setString(7,  zipCode);

        if (birthDate.isBlank()) {
            ps.setNull(8, java.sql.Types.DATE);
        } else {
            ps.setString(8, birthDate);   // formato 'YYYY-MM-DD'
        }

        ps.setString(9,  username);
        ps.setString(10, password);      
        ps.setString(11, "USER");        // todos los que se añadan desde aquí serán USER

        int rows = ps.executeUpdate();

        if (rows > 0) {
            JOptionPane.showMessageDialog(this, "Usuario agregado correctamente.");
            loadUsers(); // refrescar tabla
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo agregar el usuario.");
        }

    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this,
                "Error al agregar usuario:\n" + e.getMessage());
    }
    }//GEN-LAST:event_BtnAgregarActionPerformed

    // Nombre: BtnEliminarActionPerformed
    // Propósito: Eliminar de la base de datos el usuario seleccionado en la tabla.
    // PreCondiciones: Debe haber una fila seleccionada y ese ID debe existir en la tabla users.
    // PostCondiciones: Si el usuario confirma, se elimina el registro de la BD y se actualiza la tabla.
    // Argumentos: evt - evento generado al presionar el botón "Eliminar".
    // Valores: No devuelve valor, solo borra el usuario y actualiza la vista.
    private void BtnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnEliminarActionPerformed
        // TODO add your handling code here:
        int fila = tblUsers.getSelectedRow();

    if (fila == -1) {
        JOptionPane.showMessageDialog(this,
                "Selecciona un usuario de la tabla para eliminar.");
        return;
    }

    DefaultTableModel model = (DefaultTableModel) tblUsers.getModel();
    Object value = model.getValueAt(fila, 0); // Columna 0 = ID

    if (value == null) {
        JOptionPane.showMessageDialog(this,
                "No se pudo obtener el ID del usuario.");
        return;
    }

    int userId = Integer.parseInt(value.toString());

    int confirm = JOptionPane.showConfirmDialog(this,
            "¿Seguro que quieres eliminar al usuario con ID " + userId + "?",
            "Confirmar eliminación",
            JOptionPane.YES_NO_OPTION);

    if (confirm != JOptionPane.YES_OPTION) {
        return;
    }

    String sql = "DELETE FROM users WHERE user_id = ?";

    try (Connection cn = DBConnection.getConnection();
         PreparedStatement ps = cn.prepareStatement(sql)) {

        ps.setInt(1, userId);
        int rows = ps.executeUpdate();

        if (rows > 0) {
            JOptionPane.showMessageDialog(this,
                    "Usuario eliminado correctamente.");
            loadUsers(); // Recargar la tabla
        } else {
            JOptionPane.showMessageDialog(this,
                    "No se eliminó ningún usuario (verifica el ID).");
        }

    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this,
                "Error al eliminar usuario:\n" + e.getMessage());
    }
    }//GEN-LAST:event_BtnEliminarActionPerformed

    // Nombre: BtnEditarActionPerformed
    // Propósito: Permitir editar los datos básicos del usuario seleccionado y guardar los cambios en la BD.
    // PreCondiciones: Debe haber un usuario seleccionado en la tabla y la conexión a la BD debe funcionar.
    // PostCondiciones: Si todo va bien, se actualiza el registro en la BD y se recarga la tabla con los nuevos datos.
    // Argumentos: evt - evento generado al presionar el botón "Editar".
    // Valores: No devuelve valor, solo actualiza la base de datos y la tabla.
    private void BtnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnEditarActionPerformed
        // TODO add your handling code here:
        int fila = tblUsers.getSelectedRow();

    if (fila == -1) {
        JOptionPane.showMessageDialog(this,
                "Selecciona un usuario de la tabla para editar.");
        return;
    }

    DefaultTableModel model = (DefaultTableModel) tblUsers.getModel();

    // Tomar los valores actuales de la fila
    Object idValue       = model.getValueAt(fila, 0); // ID
    String firstName     = (String) model.getValueAt(fila, 1);
    String middleName    = (String) model.getValueAt(fila, 2);
    String lastName      = (String) model.getValueAt(fila, 3);
    String phone         = (String) model.getValueAt(fila, 4);
    String address       = (String) model.getValueAt(fila, 5);
    String city          = (String) model.getValueAt(fila, 6);
    String zipCode       = (String) model.getValueAt(fila, 7);
    Object birthDateObj  = model.getValueAt(fila, 8);

    String birthDateStr = (birthDateObj == null) ? "" : birthDateObj.toString();

    int userId = Integer.parseInt(idValue.toString());

    // Pedir nuevos valores (prellenados con lo actual)
    firstName  = JOptionPane.showInputDialog(this, "First name:", firstName);
    if (firstName == null) return;

    middleName = JOptionPane.showInputDialog(this, "Middle name:", middleName);
    if (middleName == null) middleName = "";

    lastName   = JOptionPane.showInputDialog(this, "Last name:", lastName);
    if (lastName == null) return;

    phone      = JOptionPane.showInputDialog(this, "Phone:", phone);
    if (phone == null) phone = "";

    address    = JOptionPane.showInputDialog(this, "Address:", address);
    if (address == null) address = "";

    city       = JOptionPane.showInputDialog(this, "City:", city);
    if (city == null) city = "";

    zipCode    = JOptionPane.showInputDialog(this, "Zip code:", zipCode);
    if (zipCode == null) zipCode = "";

    birthDateStr = JOptionPane.showInputDialog(
            this, "Birth date (YYYY-MM-DD, o vacío):", birthDateStr);
    if (birthDateStr == null) birthDateStr = "";

    String sql = "UPDATE users SET " +
                 "first_name = ?, middle_name = ?, last_name = ?, " +
                 "phone = ?, address = ?, city = ?, zip_code = ?, birth_date = ? " +
                 "WHERE user_id = ?";

    try (Connection cn = DBConnection.getConnection();
         PreparedStatement ps = cn.prepareStatement(sql)) {

        ps.setString(1, firstName);
        ps.setString(2, middleName);
        ps.setString(3, lastName);
        ps.setString(4, phone);
        ps.setString(5, address);
        ps.setString(6, city);
        ps.setString(7, zipCode);

        if (birthDateStr.isBlank()) {
            ps.setNull(8, java.sql.Types.DATE);
        } else {
            ps.setString(8, birthDateStr);
        }

        ps.setInt(9, userId);

        int rows = ps.executeUpdate();

        if (rows > 0) {
            JOptionPane.showMessageDialog(this, "Usuario actualizado correctamente.");
            loadUsers(); // recargar la tabla
        } else {
            JOptionPane.showMessageDialog(this, "No se actualizó el usuario (verifica el ID).");
        }

    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this,
                "Error al actualizar usuario:\n" + e.getMessage());
    }

    }//GEN-LAST:event_BtnEditarActionPerformed

