    // Nombre: loadUsers
    // Propósito: Leer todos los usuarios de la base de datos y mostrarlos en la tabla tblUsers.
    // PreCondiciones: La conexión a la base de datos debe funcionar y el modelo de la tabla debe estar inicializado.
    // PostCondiciones: La tabla se limpia y se vuelve a llenar con los datos actuales de la tabla users.
    // Argumentos: Ninguno.
    // Valores: No devuelve valor, solo actualiza la interfaz con la información de los usuarios.
    private void loadUsers() {
    DefaultTableModel model = (DefaultTableModel) tblUsers.getModel();
    // Limpiar filas actuales
    model.setRowCount(0);

    String sql = "SELECT user_id, first_name, middle_name, last_name, " +
                 "phone, address, city, zip_code, birth_date " +
                 "FROM users ORDER BY user_id";

    try (Connection cn = DBConnection.getConnection();
         PreparedStatement ps = cn.prepareStatement(sql);
         ResultSet rs = ps.executeQuery()) {

        while (rs.next()) {
            Object[] row = new Object[9];
            row[0] = rs.getInt("user_id");
            row[1] = rs.getString("first_name");
            row[2] = rs.getString("middle_name");
            row[3] = rs.getString("last_name");
            row[4] = rs.getString("phone");
            row[5] = rs.getString("address");
            row[6] = rs.getString("city");
            row[7] = rs.getString("zip_code");
            row[8] = rs.getDate("birth_date");

            model.addRow(row);
        }

    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this,
                "Error cargando usuarios:\n" + e.getMessage());
    }
}
